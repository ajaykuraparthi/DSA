class Solution {
    public int maxProfit(int[] prices) {

      int ans=0;
    
        for(i=0;i<=prices.length;i++){
           int buyday = prices.Mathmax(prices[i]);

            for(int j=buyday;j<prices.lenght;j++){
                int sellday = prices.Mathmax(prices[j]);

                if(sellday>buyday){
                    ans+=sellday+buyday;
                }
            }
        } 

    }
}